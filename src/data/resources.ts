export type ThemeSwatch = { labelKey: MessageKey; color: string };

// 基础 4 色：back/text 决定整体明暗基调，hilited_candidate_back/text 决定选中候选的视觉效果——
// 这四个字段共同决定了配色的核心观感；border 在缩略图里参考价值有限（常与 back 同色、或干脆未设置），不再占用色块位
export function getThemeSwatches(theme: RimeTheme): ThemeSwatch[] {
  const slots: Array<ThemeSwatch | undefined> = [
    theme.colors.backColor ? { labelKey: "ui.swatch.back", color: theme.colors.backColor } : undefined,
    theme.colors.textColor ? { labelKey: "ui.swatch.text", color: theme.colors.textColor } : undefined,
    theme.colors.hilitedCandidateBackColor ? { labelKey: "ui.swatch.highlightBack", color: theme.colors.hilitedCandidateBackColor } : undefined,
    theme.colors.hilitedCandidateTextColor ? { labelKey: "ui.swatch.highlightText", color: theme.colors.hilitedCandidateTextColor } : undefined,
  ];
  return slots.filter((swatch): swatch is ThemeSwatch => Boolean(swatch));
}
